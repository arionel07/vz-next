export function getPathLocale(pathname: string | null | undefined): StoreLocale {
  return pathname?.split('/')[1] === 'ro' ? 'ro' : 'ru'
}

export function localizedPath(pathname: string, locale: StoreLocale) {
  const suffixIndex = pathname.search(/[?#]/)
  const path = suffixIndex < 0 ? pathname : pathname.slice(0, suffixIndex)
  const suffix = suffixIndex < 0 ? '' : pathname.slice(suffixIndex)

  if (path === '/' || path === '') return `/${locale}${suffix}`
  if (!path.startsWith('/')) return pathname
  if (path.startsWith('/api/') || path.startsWith('/_next/')) return pathname
  if (path === '/get-app') return pathname

  const segments = path.split('/').filter(Boolean)
  if (segments[0] === 'ru' || segments[0] === 'ro') segments.shift()
  if (!segments.length) return `/${locale}${suffix}`

  segments[0] = pathAliases[locale][segments[0]] ?? segments[0]
  if (!supportedRouteHeads[locale].has(segments[0])) return `/${locale}${suffix}`

  return `/${locale}/${segments.join('/')}${suffix}`
}

export function localeSwitchPath(pathname: string, locale: StoreLocale) {
  return localizedPath(pathname, locale)
}
